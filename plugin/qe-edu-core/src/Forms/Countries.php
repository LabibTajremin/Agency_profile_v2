	/**
	 * Countries as editable text, one per line.
	 *
	 * @return string
	 */
	public static function as_text() {
		return implode( "\n", self::all() );
	}

	/**
	 * Parse an editable list (one per line) into names.
	 *
	 * @param string $text Text.
	 * @return string[]
	 */
	public static function parse( $text ) {
		return array_values( array_filter( array_map( 'trim', explode( "\n", str_replace( "\r", '', (string) $text ) ) ), 'strlen' ) );
	}
